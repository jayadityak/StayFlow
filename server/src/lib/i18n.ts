export function T(lang: string, key: string, vars: Record<string, string | number> = {}): string {
  const l = (SUPPORTED_LANGS.includes(lang as Lang) ? lang : 'en') as Lang;
  let str = T_MAP[l][key] ?? T_MAP['en'][key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  }
  return str;
}

/** Always returns the English version of a translation key. */
export function TEN(key: string, vars: Record<string, string | number> = {}): string {
  return T('en', key, vars);
}
